"""Export a build (PRD section 15): values only, sheet "Schedule", bold frozen filtered header."""

from __future__ import annotations

import csv
from datetime import datetime
from pathlib import Path

from .models import BuildResult, GeneratorConfig
from .text import to_text


def export_name(cfg: GeneratorConfig, generator_name: str, now: datetime | None = None, ext: str = ".xlsx") -> str:
    if cfg.doc_number.strip():
        rev = f"_{cfg.doc_revision.strip()}" if cfg.doc_revision.strip() else ""
        title = f" {cfg.doc_title.strip()}" if cfg.doc_title.strip() else ""
        name = f"{cfg.doc_number.strip()}{rev}{title}"
    else:
        name = f"{generator_name} Output {(now or datetime.now()).strftime('%Y%m%d-%H%M')}"
    return "".join("_" if ch in '<>:"/\\|?*' else ch for ch in name) + ext


def export_xlsx(result: BuildResult, cfg: GeneratorConfig, path: str | Path, build_id: str = "") -> Path:
    path = Path(path)
    path.write_bytes(xlsx_bytes(result, cfg, build_id))
    return path


def xlsx_bytes(result: BuildResult, cfg: GeneratorConfig, build_id: str = "",
               summary: list[tuple[str, str | int | float | None]] | None = None) -> bytes:
    """`summary`: label and value lines, written to a second sheet, "Panel"."""
    import io

    from openpyxl import Workbook
    from openpyxl.styles import Font
    from openpyxl.utils import get_column_letter

    wb = Workbook()
    ws = wb.active
    ws.title = "Schedule"
    ws.append(result.header)
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in result.rows:
        ws.append([v if not (isinstance(v, str) and v.startswith("=")) else "'" + v for v in r.cells])
    ws.freeze_panes = "A2"
    if result.header:
        ws.auto_filter.ref = f"A1:{get_column_letter(len(result.header))}{max(1, len(result.rows) + 1)}"
    for i, h in enumerate(result.header, start=1):
        width = max([len(to_text(h))] + [len(to_text(r.cells[i - 1])) for r in result.rows[:500] if i - 1 < len(r.cells)])
        ws.column_dimensions[get_column_letter(i)].width = min(60, max(8, width + 2))
    if summary:
        extra = wb.create_sheet("Panel")
        for label, value in summary:
            extra.append([label, value if not (isinstance(value, str) and value.startswith("=")) else "'" + value])
        for c in extra["A"]:
            c.font = Font(bold=True)
        extra.column_dimensions["A"].width = max(len(label) for label, _ in summary) + 2
        extra.column_dimensions["B"].width = min(60, max([8] + [len(to_text(v)) + 2 for _, v in summary]))
    p = wb.properties
    p.title = cfg.doc_title or None
    if cfg.doc_number:
        p.subject = f"{cfg.doc_number} Rev {cfg.doc_revision}".strip()
    p.description = f"Generated by {result.engine_version}" + (f", build {build_id}" if build_id else "")
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def csv_bytes(result: BuildResult, date_format: str = "%d/%m/%Y") -> bytes:
    import io
    buf = io.StringIO(newline="")
    w = csv.writer(buf)
    w.writerow(result.header)
    for r in result.rows:
        w.writerow([to_text(v, date_format) if not isinstance(v, bool) else ("TRUE" if v else "FALSE") for v in r.cells])
    return buf.getvalue().encode("utf-8-sig")


def export_csv(result: BuildResult, path: str | Path, date_format: str = "%d/%m/%Y") -> Path:
    path = Path(path)
    path.write_bytes(csv_bytes(result, date_format))
    return path
